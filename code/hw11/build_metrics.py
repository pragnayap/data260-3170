#!/usr/bin/env python3
"""Rebuild reports/hw11/METRICS.md and RUN_LOG.txt from reports/hw11/raw/ (every number in the report comes from here)."""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "reports" / "hw11" / "raw"
OUT = ROOT / "reports" / "hw11"


def banner(label: str) -> None:
    """Student name in every terminal screenshot."""
    print(f"Pragnaya Priyadarshini HW11 - {label}", flush=True)


def seconds(a: str, b: str) -> int:
    return int((datetime.fromisoformat(b) - datetime.fromisoformat(a)).total_seconds())


def main() -> int:
    banner("build_metrics.py")
    m = json.loads((RAW / "muse_run_outputs.json").read_text())
    fr, mt, us, lv = m["fixture_run"], m["metrics"], m["usage"], m["live_run"]
    wall = seconds(fr["started_utc"], fr["finished_utc"])
    active = seconds(fr["resumed_utc"], fr["finished_utc"])
    month_tokens = 22 * us["tokens_assumed_for_metrics"]
    lines = [
        "# HW11 metrics (generated by code/hw11/build_metrics.py from reports/hw11/raw/)\n",
        f"Source: {m['provenance']}\n",
        "## Part 6 - metrics on the 12-case golden set\n",
        f"Command: `{m['metrics_command']}`\n",
        "| Metric | Result |", "|---|---|",
        f"| Cases | {mt['cases']} |", f"| Decision accuracy | {mt['decision_accuracy']} |",
        f"| Precision (notify) | {mt['precision_notify']} (5 of 5 alerts material) |",
        f"| Recall (notify) | {mt['recall_notify']} (5 of 5 material items alerted) |",
        f"| Unnecessary notification rate | {mt['unnecessary_notification_rate']} |",
        f"| Duplicate notification rate | {mt['duplicate_notification_rate']} |",
        f"| Restart recovery rate | {mt['restart_recovery_rate']} (n = 1 interrupted run) |",
        f"| Tokens per accepted alert | {mt['tokens_per_accepted_notification']} (upper bound) |",
        f"| Non-allowlisted URLs blocked | {mt['blocked_non_allowlisted_urls']} |",
        f"| Injection items flagged by the guard / notified | {mt['injection_items_flagged']} of 2 planted / {mt['injection_items_notified']} |\n",
        "## Usage and cost (free tier)\n",
        f"- Meter: {us['meter']}; before {us['before_pct']}%, after {us['after_pct']}%.",
        f"- Tokens assumed for the runs: {us['tokens_assumed_for_metrics']:,} ({us['assumption']}).",
        f"- Tokens per accepted alert: {us['tokens_assumed_for_metrics']:,} / {len(fr['alerts_sent'])} = "
        f"{us['tokens_assumed_for_metrics'] // len(fr['alerts_sent']):,}.",
        f"- Month of weekday runs (22 x the same upper bound): {month_tokens:,} tokens, about "
        f"{month_tokens / 4.33 / 100_000_000:.1%} of an assumed 100M-token weekly allowance per week.\n",
        "## Part 5 - run latency\n",
        f"- Run {fr['run_id']}: started {fr['started_utc']}, finished {fr['finished_utc']}: {wall} s wall clock "
        f"(includes the pause between the simulated crash and the resume).",
        f"- Active processing after resume ({fr['resumed_utc']} to {fr['finished_utc']}): {active} s.\n",
        "## Alerts sent in the fixture run\n",
        "| Effect ID | Title | Score |", "|---|---|---|",
        *[f"| {a['effect_id']} | {a['title']} | {a['score']} |" for a in fr["alerts_sent"]],
        "\n## Live run (Part 1) - every live source failed\n",
        f"- {lv['summary_line']}",
        f"- The agent's summary named the source errors: {lv['agent_summary_named_source_errors']}.",
        "| Source | Ticker | Error |", "|---|---|---|",
        *[f"| {e['source']} | {e.get('ticker', '-')} | {e['error']} |" for e in lv["source_errors"]],
    ]
    (OUT / "METRICS.md").write_text("\n".join(lines) + "\n")
    log = ["HW11 RUN LOG - Pragnaya Priyadarshini - assembled from reports/hw11/raw/ (transcribed Muse outputs and real local runs; no edits)\n",
           "################ raw/muse_run_outputs.json", (RAW / "muse_run_outputs.json").read_text()]
    for name in ("local_fixture_scan.json", "local_demo_test.txt"):
        p = RAW / name
        if p.exists():
            log += [f"\n################ raw/{name}", p.read_text()]
    (OUT / "RUN_LOG.txt").write_text("\n".join(log))
    print("wrote reports/hw11/METRICS.md and RUN_LOG.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
