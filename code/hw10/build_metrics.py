#!/usr/bin/env python3
"""Rebuild reports/hw10/METRICS.md from reports/hw10/raw/ (every number in the report comes from here, none is typed by hand)."""
from __future__ import annotations

import json
import statistics as st
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "reports" / "hw10" / "raw"


def banner(label: str) -> None:
    """Student name in every terminal screenshot."""
    print(f"Pragnaya Priyadarshini HW10 - {label}", flush=True)


def load(name):
    try:
        return json.loads((RAW / name).read_text())
    except (OSError, ValueError):
        return None


def main() -> int:
    banner("build_metrics.py")
    out = ["# HW10 metrics (generated by code/hw10/build_metrics.py from reports/hw10/raw/)\n"]
    lat, runs, ex = load("latency_stats.json"), load("latency_runs.json"), load("trace_examples.json")

    out.append("## Part 4.3 - stage latency, 50 confirmed cache-miss requests\n")
    if lat and runs:
        out.append(f"- requests: {lat['n_requests']} (all confirmed cache misses; hits skipped during the run: {len(runs['skipped_hits'])}; threshold {runs.get('threshold')})")
        e = lat["end_to_end_ms"]
        out.append(f"- end-to-end (cache_lookup start -> final answer): p50 {e['p50']} ms, p95 {e['p95']} ms, mean {e['mean']} ms, max {max(r['e2e_ms'] for r in runs['requests']):.1f} ms")
        out.append(f"- dominant stage: **{lat['dominant_stage']}** · request-path stages cover {lat['request_path_stages_pct_total']}% of end-to-end\n")
        out.append("| Stage | n | p50 (ms) | p95 (ms) | % of cache-miss end-to-end |\n|---|---|---|---|---|")
        for k, v in lat["stages"].items():
            out.append(f"| {k} | {v['n']} | {v['p50_ms']} | {v['p95_ms']} | {v['pct_of_end_to_end']} |")
        out.append("")
        if lat.get("cache_hit_latency_ms"):
            h = lat["cache_hit_latency_ms"]
            out.append(f"Cache-hit latency (separate metric, n={h['n']} repeats of already-answered questions): p50 {h['p50']} ms, p95 {h['p95']} ms, max {h['max']} ms\n")
    else:
        out.append("pending\n")

    out.append("## Part 4.2 - required example traces\n")
    if ex:
        out += [f"- cache hit : `{ex['cache_hit']['trace_id']}` (similarity {ex['cache_hit']['similarity']}, {ex['cache_hit']['e2e_ms']} ms)",
                f"- cache miss: `{ex['cache_miss']['trace_id']}` ({ex['cache_miss']['e2e_ms']} ms, {ex['cache_miss']['note']})",
                f"- failed    : `{ex['failed']['trace_id']}` - failing stage **{ex['failed']['failing_stage']}**, error: {ex['failed']['error']}\n"]
    else:
        out.append("pending\n")

    out.append("## Part 2 - evaluator results (DeepEval GEval, local judge, 1-5)\n")
    res = load("eval_results.json")
    ok = [v for v in (res or {}).values() if v.get("status") == "ok"]
    if ok:
        out.append(f"- evaluated requests: {len(ok)} · judge: {ok[0]['judge']}\n")
        out.append("| Criterion | mean | min | max | distribution |\n|---|---|---|---|---|")
        for label, key in (("Plan Quality", "plan_quality"), ("Writer Helpfulness", "writer_helpfulness"), ("Final Answer Helpfulness", "final_helpfulness")):
            s = [v[key]["score"] for v in ok if v[key]["score"] is not None]
            out.append(f"| {label} | {st.mean(s):.2f} | {min(s)} | {max(s)} | {dict(sorted(Counter(s).items()))} |")
        d = [v["final_vs_draft"]["difference"] for v in ok if v["final_vs_draft"]["difference"] is not None]
        same = sum(1 for v in ok if v["draft"].strip() == (v["final_answer"] or "").strip())
        out.append(f"\nFinal-vs-Draft: mean difference {st.mean(d):+.2f}; distribution {dict(sorted(Counter(d).items()))}; "
                   f"final answer identical to the draft in {same}/{len(ok)} requests (the Reviewer is rule-based and never edits text).")
        ev = [v["evaluation_ms"] for v in ok]
        out.append(f"Evaluation latency per request: p50 {st.median(ev):.0f} ms, max {max(ev):.0f} ms (3 judge calls on the same CPU as the models).\n")
        out.append("| trace | Plan | Draft | Final | Final - Draft | question |\n|---|---|---|---|---|---|")
        for v in ok:
            out.append(f"| {v['trace_id'][:8]} | {v['plan_quality']['score']} | {v['writer_helpfulness']['score']} | {v['final_helpfulness']['score']} | "
                       f"{v['final_vs_draft']['difference']} | {v['question'][:70]} |")
        out.append("")
    else:
        out.append("pending\n")

    out.append("## Part 3 - judge validation\n")
    val, jr = load("judge_validation.json"), load("judge_runs.json")
    if val and jr:
        p, r = val["part_3_2_run1_vs_human"], val["repeatability"]
        out.append(f"- settings: {val['settings']}")
        out.append(f"- Spearman (run 1 vs human): **{p['spearman']}** · mean absolute difference: **{p['mean_abs_diff']}** · signed bias (judge - human): {p['mean_signed_diff_judge_minus_human']}")
        out.append(f"- repeatability over {val['n_runs']} runs: {r['cases_whose_score_changed_across_runs']}/{r['cases_compared']} cases changed "
                   f"({r['fraction_cases_changed']}); {r['fraction_pair_comparisons_changed']} of run-pair comparisons changed; mean abs change {r['mean_abs_change']}, max {r['max_abs_change']}")
        out.append(f"- human label distribution: {val['human_label_distribution']}\n")
        out.append("| run | n scored | Spearman | mean abs diff |\n|---|---|---|---|")
        for i, e in enumerate(val["each_run_vs_human"], 1):
            out.append(f"| {i} | {e['n_scored']} | {e['spearman']} | {e['mean_abs_diff']} |")
        out.append("")
    else:
        out.append("pending (needs the 20 hand-assigned human labels, committed, before the judge is run)\n")

    (ROOT / "reports" / "hw10" / "METRICS.md").write_text("\n".join(out) + "\n")
    print("wrote reports/hw10/METRICS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
