#!/usr/bin/env python3
"""Rebuild reports/hw09/METRICS.md from reports/hw09/raw/*.json (numbers only; the prose lives in REPORT_NOTES.md)."""
from __future__ import annotations

import json

import common

RAW = common.RAW
OUT = common.ROOT / "reports" / "hw09" / "METRICS.md"


def load(name):
    p = RAW / name
    return json.loads(p.read_text()) if p.exists() else None


def main() -> int:
    L = ["# HW9 metrics (generated by code/hw09/build_metrics.py from reports/hw09/raw/)", ""]
    p2 = load("part2_results.json")
    if p2:
        s = p2["summary"]
        L += ["## Part 2 - semantic cache, threshold 0.85, 14 queries", "",
              f"- hit rate: **{s['hit_rate_pct']}%** ({s['hits']}/{s['queries']})",
              f"- average latency, cached: **{s['avg_latency_cached_ms']} ms**; not cached: **{s['avg_latency_not_cached_ms']} ms**", "",
              "| # | kind | is_cached | similarity | latency (ms) | query |", "|---|---|---|---|---|---|"]
        for i, r in enumerate(p2["results"], 1):
            sim = "n/a" if r["similarity"] is None else f"{r['similarity']:.4f}"
            L.append(f"| {i} | {r['kind']} | {r['is_cached']} | {sim} | {r['latency_ms']:.1f} | {r['query']} |")
        L.append("")
    p3 = load("part3_sweep.json")
    if p3:
        L += ["## Part 3.2 / 3.4 - threshold sweep (40 labeled cases)", "",
              f"Cost model: cache miss = ${p3['costs']['cache_miss_usd']:.2f}, false hit = ${p3['costs']['false_hit_usd']:.2f}. "
              f"Mean measured agent latency (20 seeds) = {p3['mean_seed_agent_ms']} ms.", "",
              "| Threshold | Hit rate | False-hit rate (of 20 should-miss) | Missed hits (of 20 should-hit) | Mean latency (ms) | Total cost ($) |",
              "|---|---|---|---|---|---|"]
        for t in p3["table"]:
            L.append(f"| {t['threshold']:.2f} | {t['hit_rate_pct']}% ({t['hits']}/40) | {t['false_hit_rate_pct']}% ({t['false_hits']}/20) | "
                     f"{t['missed_hits']} | {t['mean_latency_ms']} | {t['total_cost_usd']} |")
        L += ["", "Sensitivity - total cost if a false hit costs $1 / $5 / $25:", "",
              "| False-hit cost | " + " | ".join(f"{t['threshold']:.2f}" for t in p3["table"]) + " |", "|---|" + "---|" * len(p3["table"])]
        for k, v in p3["sensitivity_total_cost_by_false_hit_cost"].items():
            L.append(f"| ${float(k):g} | " + " | ".join(str(v[str(t['threshold'])]) for t in p3["table"]) + " |")
        L += ["", "Per-group hits (of 10 each):", "", "| Threshold | exact_duplicate | paraphrase | near_miss | unrelated |", "|---|---|---|---|---|"]
        for th in sorted({r["threshold"] for r in p3["rows"]}):
            g = {k: sum(1 for r in p3["rows"] if r["threshold"] == th and r["group"] == k and r["hit"])
                 for k in ("exact_duplicate", "paraphrase", "near_miss", "unrelated")}
            L.append(f"| {th:.2f} | {g['exact_duplicate']} | {g['paraphrase']} | {g['near_miss']} | {g['unrelated']} |")
        fh = p3.get("example_false_hit_at_0.85")
        if fh:
            L += ["", "### Part 3.3 - one false hit in full (threshold 0.85, highest-similarity false hit)", "",
                  f"- cached query: {fh['nearest_cached_query']!r}", f"- incoming query ({fh['case']}): {fh['query']!r}",
                  f"- similarity: **{fh['similarity']}**", f"- cached answer returned: {fh['nearest_cached_answer']!r}",
                  f"- correct answer (from s3170_rel): **{fh['correct_answer']}**"]
        from qa_agent import extract_entities
        L += ["", "### Supplement (computed offline from the same rows, no relabeling) - hit only if the incoming query names the same "
              "route/incident as the cached one", "",
              "| Threshold | Hits | False hits | Missed hits |", "|---|---|---|---|"]
        for th in sorted({r["threshold"] for r in p3["rows"]}):
            rr = [r for r in p3["rows"] if r["threshold"] == th]
            g = [r for r in rr if r["hit"] and extract_entities(r["query"]) == extract_entities(r["nearest_cached_query"])]
            L.append(f"| {th:.2f} | {len(g)} | {sum(r['expect'] == 'miss' for r in g)} | "
                     f"{sum(1 for r in rr if r['expect'] == 'hit' and r not in g)} |")
        L += ["", "Similarity of the nearest cached query, per case (threshold-independent):", "", "| case | group | similarity |", "|---|---|---|"]
        for r in [r for r in p3["rows"] if r["threshold"] == 0.75]:
            L.append(f"| {r['case']} | {r['group']} | {r['similarity']} |")
        L.append("")
    st = load("part3_stale.json")
    if st:
        L += ["## Part 3.5 - stale answer and invalidation", "",
              f"- route {st['route']}, agency {st['original_agency']!r} -> {st['new_agency']!r} (restored afterwards)",
              f"- stale hit (no invalidation): {st['stale_hit']['answer']!r}",
              f"- after invalidation: is_cached={st['after_invalidation']['is_cached']}, {st['after_invalidation']['answer']!r}",
              f"- fresh hit afterwards: is_cached={st['fresh_hit']['is_cached']}, version_check_ms={st['fresh_hit']['version_check_ms']}", ""]
    v = load("part4_variants.json")
    if v:
        L += ["## Part 4.4 - four variants on test_data.json", "", "| Variant | Correct | Incorrect | Avg attempts | Avg latency (s) |", "|---|---|---|---|---|"]
        for s in v["summary"]:
            L.append(f"| {s['variant']} | {s['correct']} | {s['incorrect']} | {s['avg_attempts']} | {s['avg_latency_s']} |")
        L.append("")
    val = load("part4_validation.json")
    if val:
        L += ["## Part 4.3 - lesson validation", "", "| Lesson | Decision | Detail |", "|---|---|---|"]
        for c in val["candidates"]:
            L.append(f"| {c['lesson_id']} | {c['decision']} | {c['note']} |")
        L.append("")
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
